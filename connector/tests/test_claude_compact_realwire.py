def test_mid_turn_compaction_does_not_collide_with_message_order_seq() -> None:
    """R4 measured a marker and an assistant reply sharing order_seq 3."""

    host = _RecordingHost()
    client = _Client(
        [
            _assistant("first reply", "a1"),
            parse_message(WIRE_STATUS_COMPACTING),
            parse_message(WIRE_COMPACT_BOUNDARY),
            _assistant("second reply", "a2"),
            _result(num_turns=1, result="second reply"),
        ]
    )

    def client_factory(sdk: Any, options: Any) -> _Client:
        _ = sdk
        client.options = options
        return client

    runtime = ClaudeRuntime(
        config=_config(),
        host=host,
        sdk_loader=_sdk,
        client_factory=client_factory,
    )

    async def _go() -> None:
        await runtime.start_turn(
            COMPACT_SESSION, COMPACT_SESSION, "hello", client_message_id="cm1"
        )
        task = runtime._sessions[COMPACT_SESSION].active_task
        if task is not None:
            await task

    asyncio.run(_go())

    # One item id may be upserted again as its state advances; two different
    # items may never claim the same slot.
    by_order: dict[int, set[str]] = {}
    for item in host.timeline_item_upserts:
        by_order.setdefault(item.order_seq, set()).add(item.id)

    duplicates = {seq: ids for seq, ids in by_order.items() if len(ids) > 1}
    assert not duplicates, f"order_seq collision between timeline items: {duplicates}"


