class _Client:
    def __init__(self, messages: list[Any]) -> None:
        self.messages = messages
        self.options: Any = None
        self.queries: list[str] = []

    async def connect(self) -> None:
        return None

    async def disconnect(self) -> None:
        return None

    async def query(self, prompt: Any) -> None:
        if not isinstance(prompt, str):
            first = [m async for m in prompt][0]
            prompt = first["message"]["content"]
        self.queries.append(prompt)

    async def receive_response(self) -> list[Any]:
        return self.messages

    def ensure_prompt_uuid(self) -> str:
        return "prompt-uuid"


class _Options:
    def __init__(self, **kwargs: Any) -> None:
        self.kwargs = kwargs


def _sdk() -> Any:
    return SimpleNamespace(
        __version__="1.0",
        ClaudeAgentOptions=_Options,
        PermissionResultAllow=SimpleNamespace,
        PermissionResultDeny=SimpleNamespace,
        list_sessions=lambda **_: [],
        get_session_info=lambda **_: None,
        get_session_messages=lambda **_: [],
    )


def _config() -> RuntimeConfig:
    return RuntimeConfig(runtime="claude", revision=1, values={"environment": {}})


async def _drive(
    messages: list[Any],
) -> tuple[_RecordingHost, _Client, ClaudeRuntime]:
    host = _RecordingHost()
    client = _Client(messages)

    def client_factory(sdk: Any, options: Any) -> _Client:
        _ = sdk
        client.options = options
        return client

    runtime = ClaudeRuntime(
        config=_config(),
        host=host,
        sdk_loader=_sdk,
        client_factory=client_factory,
    )
    result = await runtime.execute_command(
        session_id="sess_realwire",
        command="compact",
        external_session_id=COMPACT_SESSION,
    )
    assert result.ok is True
    task = runtime._sessions["sess_realwire"].active_task
    if task is not None:
        await task
    return host, client, runtime


def _markers(host: _RecordingHost) -> list[Any]:
    return [i for i in host.timeline_item_upserts if i.type == "marker"]


def _users(host: _RecordingHost) -> list[Any]:
    return [i for i in host.timeline_item_upserts if i.role == "user"]


