def test_real_wire_command_replay_publishes_one_completed_marker() -> None:
    host, client, _ = asyncio.run(
        _drive(
            [
                parse_message(WIRE_STATUS_COMPACTING),
                parse_message(WIRE_INIT),
                parse_message(WIRE_COMPACT_BOUNDARY),
                parse_message(WIRE_SUMMARY),
                parse_message(WIRE_STDOUT),
                _result(),
            ]
        )
    )

    assert client.queries == ["/compact"], "the command must reach the CLI verbatim"
    assert _users(host) == [], "a command turn must never publish a user bubble"
    markers = _markers(host)
    # Dispatched, then the CLI's own start frame, then the boundary. All three
    # flip one item id instead of stacking three separators.
    assert [m.content["state"] for m in markers] == [
        "started",
        "started",
        "completed",
    ], "real wire should drive the running -> completed transition"
    assert markers[0].order_seq == markers[-1].order_seq, (
        "the marker must flip in place on one item id, not stack"
    )
    assert len({m.id for m in markers}) == 1
    assert markers[-1].content["preTokens"] == 35134
    assert markers[-1].content["trigger"] == "manual"


def test_real_wire_command_replay_always_leaves_a_verdict() -> None:
    """A command turn the CLI never acknowledges must still settle."""

    host, _, _ = asyncio.run(_drive([parse_message(WIRE_INIT), _result()]))

    markers = _markers(host)
    assert [m.content["state"] for m in markers] == ["started", "failed"]
    assert [m.status for m in markers] == ["running", "failed"]
    assert len({m.id for m in markers}) == 1


