"""Replay the REAL 2026-10-02 /compact wire payloads through the Claude runtime.

Why this file exists
--------------------
`tests/test_claude_commands.py` builds the compaction fixtures from the SDK's
own message parser, so it is safe from a shape the CLI never sends. This file
goes one step further: it carries the **verbatim** JSONL control frames captured
off a real `claude` CLI 2.1.284 / SDK 0.2.161 run, with nothing invented, and
pushes them through the real `ClaudeRuntime.execute_command("compact")` path.
If a future refactor reintroduces a hand-built fixture shape, the mismatch shows
up here first.

The frames matter because the SDK's `_internal/message_parser.py` parses every
non-task system message into

    SystemMessage(subtype=<str>, data=<the whole raw payload dict>)

so `status`, `compact_result` and `compactMetadata` are reachable only through
`.data`, never as attributes.

Captured payload source:
  /tmp/probe-compact-detail.py, CLI 2.1.284, sdk 0.2.161,
  session fd17cdec-ea63-4209-b810-954e732c9765.
"""

