// Run after installing web-next dependencies; no runtime web dependency on iOS.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ios = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const modules = args.find(value => !value.startsWith('--')) ?? path.join(ios, '..', 'web-next', 'node_modules');
const require = createRequire(path.join(modules, '_symbols.cjs'));
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const icons = require('lucide-react');
const mapping = JSON.parse(fs.readFileSync(path.join(ios, 'Design/Symbols.json'), 'utf8'));
// Lucide draws every glyph at 2/24 of the frame. The official Anthropicon
// artwork it sits beside measures ~8% of the frame (median 0.080 across
// fileAdd/agent/fastforward/connectors/extendedThinking), so the 2/24 default
// reads a shade heavy in the same row (pp 2026-11-19). 1.8 measures 0.0807.
const strokeWidths = { Boxes: 1.8 };
const app = path.join(ios, 'Agents Anywhere/Agents Anywhere');
// Xcode strips a trailing 'Image' from asset symbols, which would collide with File.
const assetName = name => name === 'FileImage' ? 'aa-ImageFile' : 'aa-' + name;
function output(filename, content) {
  if (check) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== content) {
      throw new Error(`Outdated Lucide resource: ${path.relative(ios, filename)}`);
    }
  } else {
    fs.mkdirSync(path.dirname(filename), { recursive: true });
    fs.writeFileSync(filename, content);
  }
}
for (const name of new Set(Object.values(mapping))) {
  if (!icons[name]) throw new Error(`Missing Lucide icon: ${name}`);
  const directory = path.join(app, 'Assets.xcassets', `${assetName(name)}.imageset`);
  const svg = renderToStaticMarkup(React.createElement(icons[name], {
    color: '#000000', size: 24, strokeWidth: strokeWidths[name] ?? 2,
  }))
    .replace(/ class="[^"]*"| aria-hidden="[^"]*"/g, '');
  output(path.join(directory, `${name}.svg`), svg + '\n');
  output(path.join(directory, 'Contents.json'), JSON.stringify({
    images: [{ filename: `${name}.svg`, idiom: 'universal' }],
    info: { author: 'xcode', version: 1 },
    properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
  }, null, 2) + '\n');
}
// The official Anthropicon set ships as hand-drawn assets in the catalog; this
// table keeps their symbol names declared here so a regeneration cannot drop
// them (before pp 2026-11-19 they were appended to the generated file by hand
// and a rerun would have erased every one).
const official = JSON.parse(fs.readFileSync(path.join(ios, 'Design/OfficialSymbols.json'), 'utf8'));
for (const [symbol, asset] of Object.entries(official)) {
  if (mapping[symbol]) {
    throw new Error(`Symbol ${symbol} is declared by both Symbols.json and OfficialSymbols.json`);
  }
  if (!fs.existsSync(path.join(app, 'Assets.xcassets', `${asset}.imageset`))) {
    throw new Error(`Missing official asset ${asset}.imageset for ${symbol}`);
  }
}
const bySymbol = (a, b) => a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0;
const generatedEntries = [
  '        // Lucide artwork (Design/Symbols.json; rendered above).',
  ...Object.entries(mapping)
    .map(([symbol, name]) => [symbol, assetName(name)])
    .sort(bySymbol)
    .map(([symbol, asset]) => `        ${JSON.stringify(symbol)}: ${JSON.stringify(asset)},`),
  '        // Official Anthropicon artwork (Design/OfficialSymbols.json; names',
  '        // declared verbatim — some ship dotted (anthropicon.pin), older ones',
  '        // hyphenated (anthropicon-agent)).',
  ...Object.entries(official)
    .sort(bySymbol)
    .map(([symbol, asset]) => `        ${JSON.stringify(symbol)}: ${JSON.stringify(asset)},`),
].join('\n');
output(path.join(app, 'Views/Components/AppSymbolAssets.swift'),
  '// Generated by ios/scripts/sync-symbols.mjs from Design/Symbols.json (Lucide)\n'
  + '// and Design/OfficialSymbols.json (official Anthropicon assets).\n'
  + 'import Foundation\n\nenum AppSymbolAssets {\n    static let names: [String: String] = [\n'
  + generatedEntries + '\n    ]\n}\n');
const version = require('lucide-react/package.json').version;
output(path.join(app, 'Resources/Notices/Lucide.txt'), `Lucide ${version}\nhttps://lucide.dev\n\n` + fs.readFileSync(path.join(modules, 'lucide-react/LICENSE'), 'utf8'));
console.log(`${check ? 'Verified' : 'Updated'} ${new Set(Object.values(mapping)).size} vector icons from Lucide ${version}.`);
