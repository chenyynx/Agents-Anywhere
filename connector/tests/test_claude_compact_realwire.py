def test_real_sdk_nests_compaction_fields_under_data() -> None:
    """Documents *why* a top-level-attribute fixture cannot see the real bug."""

    message = parse_message(WIRE_STATUS_COMPACTING)
    assert type(message).__name__ == "SystemMessage"
    # The parser puts the whole payload in `.data`; nothing is promoted out.
    assert message.data["status"] == "compacting"
    assert not hasattr(message, "status")
    assert not hasattr(message, "compact_metadata")
    assert not hasattr(message, "compactMetadata")

    boundary = parse_message(WIRE_COMPACT_BOUNDARY)
    assert boundary.data["compactMetadata"]["preTokens"] == 35134
    assert not hasattr(boundary, "compactMetadata")


